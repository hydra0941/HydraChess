int evaluate(const Position& pos) {
    int score = 0;
    for(int pt = PAWN; pt <= KING; pt++) {
        Bitboard w = pos.pieces(WHITE, PieceType(pt));
        while (w) {
            Square s = pop_lsb(w);
            score += PieceValue[pt] + PST[pt][s ^ 56];
        }
        Bitboard b = pos.pieces(BLACK, PieceType(pt));
        while (b) {
            Square s = pop_lsb(b);
            score -= PieceValue[pt] + PST[pt][s];
        }
    }

    return pos.side_to_move() == WHITE ? score : -score;
}

